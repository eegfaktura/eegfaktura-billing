package org.vfeeg.eegfaktura.billing.rest;

import com.auth0.jwt.JWT;
import com.auth0.jwt.JWTCreator;
import com.auth0.jwt.algorithms.Algorithm;

import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyPairGenerator;
import java.security.KeyStore;
import java.security.cert.Certificate;
import java.security.interfaces.RSAPrivateKey;
import java.security.interfaces.RSAPublicKey;
import java.time.Instant;
import java.util.List;

/**
 * Signs bearer tokens for the web-layer tests with a test-only key pair generated at class load
 * (the JDK's {@code keytool}, self-signed certificate, never committed: the secret scan refuses any
 * private key). The certificate lands in a temp file, {@link #CERT_FILE}, which {@code WebSliceTest}
 * hands to {@code JwtTokenService} as {@code app.jwt-public-key-file}. On {@code master} {@link
 * org.vfeeg.eegfaktura.billing.security.JwtTokenService} reads only the claims {@code tenant[]},
 * {@code access_groups[]} and {@code preferred_username}; no issuer, no client.
 */
public final class TestTokens {

    private static final String ALIAS = "jwt";
    private static final char[] STORE_PASSWORD = "test-only".toCharArray();

    /** The self-signed certificate of the generated key pair, DER, in a temp file. */
    public static final Path CERT_FILE;

    public static final String OWN = "RC100001";
    public static final String FOREIGN = "RC999999";
    public static final String ADMIN_GROUP = "EEG_ADMIN";

    private static final Algorithm ALGORITHM;

    static {
        try {
            KeyStore store = generateKeyStore();
            Certificate certificate = store.getCertificate(ALIAS);
            CERT_FILE = Files.createTempFile("billing-test-jwt-", ".der");
            CERT_FILE.toFile().deleteOnExit();
            Files.write(CERT_FILE, certificate.getEncoded());
            ALGORITHM = Algorithm.RSA256((RSAPublicKey) certificate.getPublicKey(),
                    (RSAPrivateKey) store.getKey(ALIAS, STORE_PASSWORD));
        } catch (Exception e) {
            throw new IllegalStateException("cannot generate the test-only JWT key pair", e);
        }
    }

    private TestTokens() {
    }

    /** "Bearer …" of an EEG_ADMIN of the own community. */
    public static String admin() {
        return bearer(token(List.of(OWN), List.of(ADMIN_GROUP)));
    }

    /** "Bearer …" of a user of the own community without the role EEG_ADMIN. */
    public static String userWithoutAdminRole() {
        return bearer(token(List.of(OWN), List.of("EEG_USER")));
    }

    /** "Bearer …" of an EEG_ADMIN of the own community, issued to the Keycloak client {@code azp}, with an e-mail. */
    public static String adminOfClient(String azp, String email) {
        return bearer(claims(List.of(OWN), List.of(ADMIN_GROUP))
                .withClaim("azp", azp).withClaim("email", email).sign(ALGORITHM));
    }

    public static String bearer(String token) {
        return "Bearer " + token;
    }

    public static String token(List<String> tenants, List<String> accessGroups) {
        return claims(tenants, accessGroups).sign(ALGORITHM);
    }

    /** Valid claims, expired two minutes ago (the service accepts 60 s leeway). */
    public static String expired() {
        return claims(List.of(OWN), List.of(ADMIN_GROUP))
                .withIssuedAt(Instant.now().minusSeconds(600))
                .withExpiresAt(Instant.now().minusSeconds(120))
                .sign(ALGORITHM);
    }

    /** Valid claims, signed with a key the service does not know. */
    public static String signedWithForeignKey() throws Exception {
        KeyPairGenerator generator = KeyPairGenerator.getInstance("RSA");
        generator.initialize(2048);
        var pair = generator.generateKeyPair();
        Algorithm foreign = Algorithm.RSA256((RSAPublicKey) pair.getPublic(), (RSAPrivateKey) pair.getPrivate());
        return claims(List.of(OWN), List.of(ADMIN_GROUP)).sign(foreign);
    }

    /** Correctly signed, but without the {@code tenant} claim. */
    public static String withoutTenantClaim() {
        return JWT.create()
                .withArrayClaim("access_groups", new String[]{ADMIN_GROUP})
                .withClaim("preferred_username", "test-admin")
                .withExpiresAt(Instant.now().plusSeconds(600))
                .sign(ALGORITHM);
    }

    private static JWTCreator.Builder claims(List<String> tenants, List<String> accessGroups) {
        return JWT.create()
                .withArrayClaim("tenant", tenants.toArray(String[]::new))
                .withArrayClaim("access_groups", accessGroups.toArray(String[]::new))
                .withClaim("preferred_username", "test-admin")
                .withIssuedAt(Instant.now())
                .withExpiresAt(Instant.now().plusSeconds(600));
    }

    /** RSA 2048 key pair with a self-signed certificate, generated by the JDK's keytool. */
    private static KeyStore generateKeyStore() throws Exception {
        Path file = Files.createTempFile("billing-test-jwt-", ".p12");
        try {
            Files.delete(file); // keytool refuses to write into an existing, empty file
            Process keytool = new ProcessBuilder(
                    Path.of(System.getProperty("java.home"), "bin", "keytool").toString(),
                    "-genkeypair", "-alias", ALIAS, "-keyalg", "RSA", "-keysize", "2048", "-validity", "1",
                    "-dname", "CN=eegfaktura-billing test-only", "-storetype", "PKCS12",
                    "-keystore", file.toString(), "-storepass", new String(STORE_PASSWORD))
                    .redirectErrorStream(true)
                    .start();
            String output = new String(keytool.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
            if (keytool.waitFor() != 0) {
                throw new IllegalStateException("keytool failed: " + output);
            }
            KeyStore store = KeyStore.getInstance("PKCS12");
            try (InputStream in = Files.newInputStream(file)) {
                store.load(in, STORE_PASSWORD);
            }
            return store;
        } finally {
            Files.deleteIfExists(file);
        }
    }
}
